    # --- Output format ---

    def test_bundle_is_valid_json_inside_loader(self):
        """The data argument to window._loadSpotSeedBundle() is valid JSON."""
        write_year_file(self.data_dir, 2022, [
            {"spot": 22.0, "metal": "silver", "timestamp": "2022-05-05 00:00:00"},
        ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        # Extract JSON between the parentheses of _loadSpotSeedBundle(...)
        start = content.index("window._loadSpotSeedBundle(") + len("window._loadSpotSeedBundle(")
        end = content.rindex(");")
        data_str = content[start:end]
        parsed = json.loads(data_str)
        self.assertIsInstance(parsed, dict)

    def test_bundle_uses_compact_json_no_spaces(self):
        """Bundle JSON is compact (no extra spaces) to minimize file size."""
        write_year_file(self.data_dir, 2022, [
            {"spot": 22.0, "metal": "silver", "timestamp": "2022-05-05 00:00:00"},
        ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        start = content.index("window._loadSpotSeedBundle(") + len("window._loadSpotSeedBundle(")
        end = content.rindex(");")
        data_str = content[start:end]
        # Compact JSON should not have ": " (colon-space) or ", " (comma-space)
        self.assertNotIn(": ", data_str)
        self.assertNotIn(", ", data_str)

    def test_output_ends_with_loader_call_terminator(self):
        """Output file ends with the ');\n' terminator of the loader call."""
        self.run_build_bundle()
        content = read_output(self.output_file)
        self.assertTrue(content.rstrip("\n").endswith(");"))

    def test_output_overwrites_existing_file(self):
        """Calling build_bundle() twice overwrites, not appends to, the output file."""
        write_year_file(self.data_dir, 2020, [
            {"spot": 25.0, "metal": "silver", "timestamp": "2020-01-01 00:00:00"},
        ])
        self.run_build_bundle()
        first_content = read_output(self.output_file)
        self.run_build_bundle()
        second_content = read_output(self.output_file)
        self.assertEqual(first_content, second_content)

    # --- Year range boundary ---

    def test_start_year_constant(self):
        """START_YEAR constant is 1968."""
        self.assertEqual(build_seed_bundle.START_YEAR, 1968)

    def test_end_year_constant_present(self):
        """END_YEAR constant is defined and reasonable (>= 2024)."""
        self.assertGreaterEqual(build_seed_bundle.END_YEAR, 2024)

    # --- Entry counting ---

    def test_total_entry_count_in_comment_matches_data(self):
        """Comment line entry count matches the actual number of valid entries."""
        write_year_file(self.data_dir, 2020, [
            {"spot": 25.0, "metal": "silver", "timestamp": "2020-01-01 00:00:00"},
            {"spot": 26.0, "metal": "silver", "timestamp": "2020-06-01 00:00:00"},
            {"spot": 1800.0, "metal": "gold", "timestamp": "2020-03-15 00:00:00"},
        ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        # Second line: "// 3 entries across 1 years"
        lines = content.split("\n")
        comment_line = lines[1]
        self.assertIn("3", comment_line)
        self.assertIn("1", comment_line)

    def test_skipped_entries_not_counted(self):
        """Invalid (skipped) entries do not appear in the total count comment."""
        write_year_file(self.data_dir, 2020, [
            {"spot": 25.0, "metal": "silver", "timestamp": "2020-01-01 00:00:00"},  # valid
            {"metal": "silver", "timestamp": "2020-02-01 00:00:00"},  # no spot — skipped
        ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        lines = content.split("\n")
        comment_line = lines[1]
        # Only 1 valid entry
        self.assertIn("1", comment_line)

    # --- Regression: bundle keys are integers (JSON parse round-trip) ---

    def test_year_keys_are_strings_in_parsed_bundle(self):
        """After JSON parsing, year keys are strings (JSON spec: object keys are always strings).
        The Python int keys from the internal dict become string keys after json.dumps → json.loads."""
        write_year_file(self.data_dir, 2022, [
            {"spot": 22.0, "metal": "silver", "timestamp": "2022-06-01 00:00:00"},
        ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        data_json = content.split("window._loadSpotSeedBundle(")[1].rstrip(");\n")
        bundle = json.loads(data_json)
        # JSON keys are strings, but in the original Python dict they were ints
        # After json.dumps → json.loads they become strings
        keys = list(bundle.keys())
        # Keys should be "2022" (string after JSON round-trip)
        self.assertIn("2022", keys)


