"""
Tests for .claude/skills/seed-sync/build-seed-bundle.py (and devops/build-seed-bundle.py)

Tests build_bundle() by patching the DATA_DIR and OUTPUT_FILE to use temp directories.
"""

import importlib.util
import json
import os
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

# ---------------------------------------------------------------------------
# Load the module under test (use the skills-sync copy added in this PR)
# ---------------------------------------------------------------------------
SCRIPT_PATH = os.path.join(
    os.path.dirname(__file__),
    "../../.claude/skills/seed-sync/build-seed-bundle.py",
)
spec = importlib.util.spec_from_file_location("build_seed_bundle", SCRIPT_PATH)
build_seed_bundle = importlib.util.module_from_spec(spec)
spec.loader.exec_module(build_seed_bundle)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def write_year_file(data_dir, year, entries):
    """Write a spot-history-{year}.json file into data_dir."""
    path = os.path.join(data_dir, f"spot-history-{year}.json")
    with open(path, "w") as f:
        json.dump(entries, f)
    return path


def read_output(output_file):
    """Read and return the text of the generated JS bundle."""
    with open(output_file) as f:
        return f.read()


