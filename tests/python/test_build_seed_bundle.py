# Tests
# ---------------------------------------------------------------------------


class TestBuildBundle(unittest.TestCase):

    def setUp(self):
        """Create a fresh temp dir for each test."""
        self._tmpdir = tempfile.TemporaryDirectory()
        self.data_dir = self._tmpdir.name
        self.output_file = os.path.join(self.data_dir, "spot-history-bundle.js")

    def tearDown(self):
        self._tmpdir.cleanup()

    def run_build_bundle(self):
        """Run build_bundle() with DATA_DIR and OUTPUT_FILE patched to temp dirs."""
        with patch.object(build_seed_bundle, "DATA_DIR", self.data_dir), \
             patch.object(build_seed_bundle, "OUTPUT_FILE", self.output_file):
            build_seed_bundle.build_bundle()

    # --- Basic output file generation ---

    def test_empty_data_dir_generates_output_file(self):
        """With no year files, output file is still created (empty bundle)."""
        self.run_build_bundle()
        self.assertTrue(os.path.exists(self.output_file))

    def test_output_file_contains_loader_call(self):
        """Output always contains window._loadSpotSeedBundle(...)."""
        self.run_build_bundle()
        content = read_output(self.output_file)
        self.assertIn("window._loadSpotSeedBundle(", content)

    def test_output_file_contains_auto_generated_comment(self):
        """Output file starts with auto-generated comment."""
        self.run_build_bundle()
        content = read_output(self.output_file)
        self.assertTrue(content.startswith("// Auto-generated by"))

    def test_output_file_contains_entry_count_comment(self):
        """Output file includes entry count and year count in header comment."""
        write_year_file(self.data_dir, 2020, [
            {"spot": 25.50, "metal": "silver", "timestamp": "2020-03-15 12:00:00"},
        ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        self.assertIn("entries", content)
        self.assertIn("years", content)

    # --- Single year file ---

    def test_single_year_single_entry(self):
        """Single year file with one entry appears in the bundle."""
        write_year_file(self.data_dir, 2020, [
            {"spot": 25.50, "metal": "silver", "timestamp": "2020-03-15 12:00:00"},
        ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        data_json = content.split("window._loadSpotSeedBundle(")[1].rstrip(");\n")
        bundle = json.loads(data_json)
        self.assertIn("2020", bundle)
        self.assertIn("silver", bundle["2020"])
        self.assertEqual(bundle["2020"]["silver"], [["03-15", 25.50]])

    def test_timestamp_extraction_yields_mm_dd(self):
        """Timestamps 'YYYY-MM-DD HH:MM:SS' are reduced to 'MM-DD'."""
        write_year_file(self.data_dir, 2021, [
            {"spot": 1800.0, "metal": "gold", "timestamp": "2021-07-04 09:00:00"},
        ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        data_json = content.split("window._loadSpotSeedBundle(")[1].rstrip(");\n")
        bundle = json.loads(data_json)
        self.assertEqual(bundle["2021"]["gold"][0][0], "07-04")

    def test_spot_price_rounded_to_two_decimals(self):
        """Spot prices are rounded to 2 decimal places."""
        write_year_file(self.data_dir, 2022, [
            {"spot": 24.5678, "metal": "silver", "timestamp": "2022-01-01 00:00:00"},
        ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        data_json = content.split("window._loadSpotSeedBundle(")[1].rstrip(");\n")
        bundle = json.loads(data_json)
        self.assertEqual(bundle["2022"]["silver"][0][1], 24.57)

    def test_integer_spot_price_preserved(self):
        """Integer-like spot prices are preserved as floats (no extra decimals)."""
        write_year_file(self.data_dir, 2022, [
            {"spot": 30.0, "metal": "silver", "timestamp": "2022-06-15 00:00:00"},
        ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        data_json = content.split("window._loadSpotSeedBundle(")[1].rstrip(");\n")
        bundle = json.loads(data_json)
        self.assertEqual(bundle["2022"]["silver"][0][1], 30.0)

    # --- Multiple metals in one year ---

    def test_multiple_metals_in_same_year(self):
        """Multiple metals in the same year file are grouped by metal."""
        write_year_file(self.data_dir, 2023, [
            {"spot": 25.0, "metal": "silver", "timestamp": "2023-01-10 00:00:00"},
            {"spot": 1900.0, "metal": "gold", "timestamp": "2023-01-10 00:00:00"},
            {"spot": 1000.0, "metal": "platinum", "timestamp": "2023-01-10 00:00:00"},
        ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        data_json = content.split("window._loadSpotSeedBundle(")[1].rstrip(");\n")
        bundle = json.loads(data_json)
        self.assertIn("silver", bundle["2023"])
        self.assertIn("gold", bundle["2023"])
        self.assertIn("platinum", bundle["2023"])

    def test_multiple_entries_same_metal_appended(self):
        """Multiple entries for the same metal in one year are all included."""
        write_year_file(self.data_dir, 2023, [
            {"spot": 25.0, "metal": "silver", "timestamp": "2023-01-10 00:00:00"},
            {"spot": 26.5, "metal": "silver", "timestamp": "2023-02-20 00:00:00"},
            {"spot": 24.0, "metal": "silver", "timestamp": "2023-03-30 00:00:00"},
        ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        data_json = content.split("window._loadSpotSeedBundle(")[1].rstrip(");\n")
        bundle = json.loads(data_json)
        self.assertEqual(len(bundle["2023"]["silver"]), 3)

    # --- Multiple years ---

    def test_multiple_year_files_all_included(self):
        """Multiple year files are all merged into the bundle."""
        for year in [2019, 2020, 2021]:
            write_year_file(self.data_dir, year, [
                {"spot": 20.0 + year - 2019, "metal": "silver",
                 "timestamp": f"{year}-06-01 00:00:00"},
            ])
        self.run_build_bundle()
        content = read_output(self.output_file)
        data_json = content.split("window._loadSpotSeedBundle(")[1].rstrip(");\n")
        bundle = json.loads(data_json)
        self.assertIn("2019", bundle)
        self.assertIn("2020", bundle)
        self.assertIn("2021", bundle)

    def test_missing_year_files_are_skipped_silently(self):
        """Years with no file are silently skipped — only present years in bundle."""
        write_year_file(self.data_dir, 2020, [
            {"spot": 25.0, "metal": "silver", "timestamp": "2020-01-01 00:00:00"},
        ])
        # No 2019 file, no 2021 file
        self.run_build_bundle()
        content = read_output(self.output_file)
        data_json = content.split("window._loadSpotSeedBundle(")[1].rstrip(");\n")
        bundle = json.loads(data_json)
        self.assertNotIn("2019", bundle)
        self.assertIn("2020", bundle)
        self.assertNotIn("2021", bundle)

